# News-Intelligencer Update-Net of Saturday September 23, 2051; the intro's "The year is 2050" is the
# sourcebook's year, as with Volume One).
# Editing inconsistencies in the book, recorded on the affected rows rather than 'fixed':
#  - The Prologue's substation strike happens on "a cold May night"; Legwork says the raid was
#    "several nights before Farseer approached the runners" (September). The notes use September.
#  - The adventure spells the nation "Athabascan Council" and "Algonkian-Manitoo"; the campaign uses
#    the sourcebook / later-canon spellings "Athabaskan Council" and "Algonkian-Manitou".
#  - Sheemahant's spell locks: the prose says Control Emotions + Influence, his gear list says
#    Influence + Control Thoughts. Marta knows all three spells; both locks are listed on his row.
#  - The Polar Bears put the HNAL camp "about 15 klicks north" of the Dead Zone; their journal and
#    the next section say 10 km.
#  - The failure handout has Captain Charles James "relieved of his position" for the ferry crash,
#    but the adventure text says the HNAL killed the entire crew an hour out of Port Hardy.
#  - Farseer has a Severe Allergy and Vulnerability to gold, and pays the team in gold nuggets.
#  - The Karma award values on p.50 did not survive the OCR; the events are listed in NOT_BUILT.
#  - Volume One (Peacekeeper) says Tsimshian left the NAN; here the HNF still lobbies the Sovereign
#    Tribal Council and the intro counts "eight native nations". Recorded on the Tsimshian row.
