SYNOPSIS = """
Seattle has Super Brawl fever: the North American Urban Brawl Championship, the top-ranked **Seattle
Screamers** against the **New York Slashers**, live from a secret Barrens brawl zone in three days.
The runners' fixer sets a 10 p.m. meet in the back room of **Club Penumbra** with a Mr. Johnson who
really is one -- **Joseph "Baby Joe" Johnson**, the Screamers' manager. His two star players, the
heavy **Punch** and the outrider **Judy**, did not exist before 2050; he wants their skeletons dug up
before the game, 5,000 nuyen each, and no contact with the players. What he does not say: he bought
the pair's contract with Mafia money, bet borrowed yakuza money on his own team, and then learned the
**Seattle Mafia** had bet on the Slashers and told Punch and Judy to throw the game or swim in Puget
Sound. He wants blackmail material to force them to win.

Legwork leads to **Bubba**, a burned-out elven cyber-mage in a Puyallup Barrens walk-up, who has
just recognized Punch and Judy as **Top Cat and Starlight** -- his old teammates from the hottest
elven shadowrun team in the sprawl, who ran for **Aztechnology** until a 2048 datasteal against
**Gentech** showed them the corp was doing genetic experiments on live elves. They trashed the data
and quit; Aztech's assassin **Kyle Morgan** and his dragon **Perianwyr** killed the rest of the team,
and the survivors left Bubba to rot. Bubba has already phoned the Aztech fixer **Keane** out of
spite. Mid-sentence, Keane's mercenaries **Stark** and **Judas** kick the door in; Bubba throws a
manaball, goes invisible and vanishes into the squatter camps.

Then everything lands on the runners at once. Mafia enforcer **Carloni** and four soldiers arrive
at their doss with a fabricated story that they work for the yakuza and a warning to stay out of
urban brawl. Their fixer summons them back to Penumbra at 11 p.m.: Bubba is dead, a pro hit in the
squatter camp (Morgan and Perianwyr), and Keane has leaked that the runners did it, so Lone Star
wants them. Morgan tails them home with ten street hitters and asks politely what they know; the
attack is coming either way, until a Harley roars down the street with Judy rigging and Punch on an
assault rifle. Morgan escapes on the dragon's back. Punch and Judy warn the runners off, name Keane,
and ask them to remember the favor.

Keane receives the team in a dusty Bellevue warehouse behind a courteous doorman who is a Force 10
earth elemental, and appears only as an astral projection: a fixer who reveals nothing, but whose
legwork trail says he stole Slashers gear and uniforms and hired a decker to find the brawl zone. The
runners report to Baby Joe the night before the game and are paid. At 8 p.m. the next night, watching
the Super Brawl in a bar, they see Kyle Morgan's face in a Slashers helmet: his men are replacing the
Slashers one by one and will murder Punch and Judy on world-wide trid. Thirty minutes to sneak past
ISSV guards, officials and seventy-two camera drones into the Kingsgate brawl zone and fight beside
the two ex-runners. Win or lose, the game is voided, the runners' faces are on the ISSV's cameras,
Baby Joe is a dead man walking, and the team is on Aztechnology's list.
"""

