# Editing inconsistencies in the book (recorded on the affected rows):
#   - Danial Simpson has Charisma 4 in Underground Man (the pry test) and Charisma 3 in the Cast of
#     Characters.
#   - Simpson says "within three days" but the synopsis gives the runners "two days"; the anniversary is
#     Friday either way.
#   - Bambra "swore off women after a particularly painful love affair during his teens" (Cast), but his
#     office tapes date the breakup with Hotama to "five years now" -- he is 28.
#   - The journalist is "Zebediah Wanderly" in the Legwork table and "Zebedian Wanderly" in the Lone Star
