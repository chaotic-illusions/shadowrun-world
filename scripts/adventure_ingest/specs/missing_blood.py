# order #25. Redmond Barrens (Hollywood, Kingsgate, Touristville) / Ravenna / Downtown, late August 2051.
# Date: the Introduction says "The year is 2050" (first-edition boilerplate), but every dated record in
# the book says August 2051 -- the chapterhouse Matrix logs Victoria's Inner Circle initiation as 8-21-51
# and the text adds "August 21 was last Sunday's date"; she "Joined: 7-12-49", which is the "two years
# ago" of the landlord and the Cat Troll; the Lone Star memo handout is stamped 05-10-51. The run itself
# is Wednesday August 24 to Friday August 26, 2051 (the Simpsons' anniversary).
# Source text: docs/Adventures/text/Shadowrun 1e - Universal Brotherhood - Missing Blood {FASA7205}.txt
