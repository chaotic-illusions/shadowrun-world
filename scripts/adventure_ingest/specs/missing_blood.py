SYNOPSIS = """
A simple affair. Fixer **Noggin** meets the runners at midday in **Ugly's** with a Renraku visitor's pass:
a nervous, pudgy UCAS sales vice-president, **Danial Simpson**, wants a present back from a girl who has
run off with it -- "no bucks, no data, no murder, just love gone sour". In the Renraku employee garage
(B3, Green 4B) Simpson, fresh from a back-slapping chat with his silver-maned father-in-law **Henry
Thomas**, hands over a photo of **Victoria Delling** (1414 Mayfair, Apartment 2W, Hollywood, Redmond)
and asks for **Blood**, a 60,000-nuyen ruby necklace by the jeweler Dante, back by 6:30 p.m. Friday --
1,000 nuyen each, 2,000 down. What he will not say unless pressed: Victoria was his mistress, his wife
**Lucile** has the receipt, he told her Blood was an anniversary present, and Friday is the anniversary.

Victoria's flat is empty and being mopped by landlord **Gary Lawson** (25 nuyen a question): a "friend"
with a signed letter broke her lease Monday and a moving van took everything. Across the hall **Mr.
Dent**, an old troll with eighteen cats, is holding her cat Nazgul and her life story -- murder-suicide
parents, institutions, a tarot reader called **Madame Ulishia** and "a policlub" that turned a
frightened child into a confident woman. Ulishia's Touristville storefront sells the same information
in 25-nuyen slices and points the team at a detective, **Patrick Bambra**, who was "following" her.
Bambra's Ravenna office (watched by five happy, brainwashed Brotherhood kids in an electric-red Westwind
with APDS in their Crusaders) holds a looped vid-message: Victoria, wearing Blood, telling Danial she
is joining the Inner Circle of the **Universal Brotherhood** -- a message Bambra lifted from Lucile's
phone tap and erased before Danial could hear it, because he fell in love with the woman on the screen.

Back at Ulishia's the door is open, the shop wrecked and two men with insect mandibles and shiny black
eyes are breaking the psychic's arm: Flesh Form Ant Warriors sent by another hive to erase what
"Ulishia" really was -- **Rektracir**, a Fly Spirit in a possessed host, raising the smothered
three-month-old **half-human, half-insect child** now lying in a hidden nursery. Bambra is found hiding
in the back office of **Superdad's**, a Kingsgate stripper bar run by his friends **Fernando** and
**Speedo**, just as four Brotherhood enforcers arrive to finish the beating they gave him at the
chapterhouse. He wants Victoria; the runners want the necklace; both are in the **Redmond
chapterhouse** at Belmont and Waveland, a converted four-plex cinema with a soup kitchen, a Force 6
astral barrier, an information-booth mage called **Judy**, a dozen guards with Flash-Paks, a Force 10
Fly Spirit sitting on fifteen boxes of loot in the basement coffers, and an Inner Circle Room where the
**Fly Queen** and four Flesh Form flies tend three cocoons. Victoria is in one, hairless and hunched,
as good as dead. Deck the chapterhouse Matrix and the Brotherhood's own records say why -- "Update
(8-23-51): Delling has already started generating interest. Proceed with Human muscle." -- and a
twenty-megapulse file called *The Universal Brotherhood* by the dead journalist **Zebediah Wanderly**
explains the rest.

Friday, 6:30, the **Glass Onion**: Simpson pays the balance, does not want to know where Victoria was,
and mentions that his father-in-law took him to "an organization that I think is really going to help
me" the night he hired the team. The bad guys win. Karma: the necklace 5, a copy of *The Universal
Brotherhood* 3, going into the Inner Circle with Bambra 2.
"""

